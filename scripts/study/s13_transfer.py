"""Study 13: does a direction taken only from other methods accelerate on held-out captions?

Studies 2 and 6 swapped directions on the 16 development prompts and picked the scale factor
on those same prompts. Here the factor is picked on the development prompts, by PickScore,
and the result is scored on COCO captions that played no part in it. Arms per host adapter,
4 steps with the host's sampler:
  <host>_tail   the adapter without its top direction per layer
  <host>_cons   the direction the other four methods agree on, at the host's per-layer strength
                times one factor
  <host>_loo    that direction at the other methods' own mean strength times one factor; nothing
                of the host is used except its sampler
  <host>_rand   a random direction per layer at the host's strength times the factor of _cons
The full adapter, its top direction and the base model without adapter are linked from study 7.

    python scripts/study/s13_transfer.py [n_captions] [block]
"""
from __future__ import annotations

import gc
import json
import sys
import time
from pathlib import Path

import torch
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
from adapters import ADAPTERS, bench, factorize, load_factors  # noqa: E402
from s2_function import HOSTS, consensus, random_direction, tail  # noqa: E402
from s7_quality import ROOT as QUALITY  # noqa: E402
from s7_quality import STEPS, coco_items  # noqa: E402
from s7_score import pick_scorer  # noqa: E402
from s12_ablation import sample  # noqa: E402

from wspd import config  # noqa: E402

GRID = (0.15, 0.25, 0.35, 0.5, 0.7, 1.0, 1.4, 2.0)
ROOT = config.RUNS / "study" / "quality_transfer"


def scaled(parts, factor: float):
    return {n: (u, s * factor, vh) for n, (u, s, vh) in parts.items()}


def leave_one_out(others: list):
    """A rank-1 change built from the other methods only: per layer, the direction they agree on,
    at the mean of their own top changes measured along it."""
    out = {}
    for n in sorted({n for f in others for n in f}):
        have = [f[n] for f in others if n in f]
        u, _, vh = factorize(torch.cat([f[0][:, :1] for f in have], 1), torch.cat([f[2][:1] for f in have], 0), 1.0)
        u, vh = u[:, :1], vh[:1]
        strength = torch.stack([f[1][0] * (u[:, 0] @ f[0][:, 0]) * (vh[0] @ f[2][0]) for f in have]).mean()
        out[n] = (u, strength[None], vh)
    return out


def main() -> None:
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 100
    block = int(sys.argv[2]) if len(sys.argv) > 2 else 50
    items = coco_items(n)
    b = bench()
    factors = {h: load_factors(h) for h in HOSTS}
    built = {}
    for h in HOSTS:
        others = [factors[k] for k in HOSTS if k != h]
        built[h] = {"cons": consensus(others, factors[h]), "loo": leave_one_out(others)}

    # The one free number per arm, chosen on the development prompts.
    path = config.RESULTS / "study" / "s13_transfer.json"
    results = json.loads(path.read_text()) if path.exists() else {"grid": list(GRID), "dev_prompts": len(b.prompts), "dev": {}}
    if any(h not in results["dev"] for h in HOSTS):
        pick = pick_scorer(b.device)

        def dev_score(parts, sampler: str) -> float:
            b.install(parts)
            return float(pick([Image.fromarray(x) for x in b.generate(sampler, STEPS)], b.prompts).mean())

        for h in HOSTS:
            if h in results["dev"]:
                continue
            t0, sampler = time.time(), ADAPTERS[h].sampler
            r = {"none": dev_score(None, sampler), "full": dev_score(factors[h], sampler)}
            for arm in ("cons", "loo"):
                r[arm] = {str(a): dev_score(scaled(built[h][arm], a), sampler) for a in GRID}
                r[f"{arm}_factor"] = max(GRID, key=lambda a: r[arm][str(a)])
            results["dev"][h] = r
            path.write_text(json.dumps(results, indent=1))
            show = lambda arm: " ".join(f"{a}:{r[arm][str(a)]:.2f}" for a in GRID)  # noqa: E731
            print(f"dev {h:7s} none {r['none']:.2f} full {r['full']:.2f} | cons {show('cons')} -> {r['cons_factor']} | loo {show('loo')} -> {r['loo_factor']} | {time.time() - t0:4.0f} s", flush=True)
        del pick, dev_score
        gc.collect()
        if str(b.device) == "mps":
            torch.mps.empty_cache()

    arms = {}
    for h in HOSTS:
        d = results["dev"][h]
        arms[f"{h}_tail"] = (h, tail(factors[h]))
        arms[f"{h}_cons"] = (h, scaled(built[h]["cons"], d["cons_factor"]))
        arms[f"{h}_loo"] = (h, scaled(built[h]["loo"], d["loo_factor"]))
        arms[f"{h}_rand"] = (h, scaled(random_direction(factors[h]), d["cons_factor"]))

    # The reference arms were generated by study 7 with the same captions, seeds and sampling code.
    for name in [f"{h}_{v}" for h in HOSTS for v in ("full", "rank1")] + [f"none_{s}" for s in sorted({ADAPTERS[h].sampler for h in HOSTS})]:
        (ROOT / name).mkdir(parents=True, exist_ok=True)
        for i in range(n):
            link = ROOT / name / f"{i:05d}.png"
            if not link.exists():
                link.symlink_to(QUALITY / name / f"{i:05d}.png")

    for start in range(0, n, block):
        for name, (h, parts) in arms.items():
            folder = ROOT / name
            folder.mkdir(parents=True, exist_ok=True)
            todo = [(i, it) for i, it in enumerate(items[start : start + block], start) if not (folder / f"{i:05d}.png").exists()]
            if not todo:
                continue
            t0 = time.time()
            b.install(parts)
            for i, it in todo:
                Image.fromarray(sample(b, it, ADAPTERS[h].sampler)).save(folder / f"{i:05d}.png")
            print(f"block {start:4d} | {name:12s} | {len(todo)} images | {time.time() - t0:4.0f} s", flush=True)
    b.install(None)


if __name__ == "__main__":
    main()
