"""Study 12: which blocks and layer types carry the acceleration, for four methods.

For each adapter, parts of it are removed and 4-step images are generated for the first COCO
captions of study 7 with the same seeds. Arms, per host:
  <host>_drop_<block>    the adapter without its down, mid or up blocks
  <host>_only_up         only the up blocks
  <host>_drop_<kind>     the adapter without one layer type (time, conv, self_attn, cross_attn, ff, attn_proj)
The full adapter and the base model without adapter are linked from study 7's images.

    python scripts/study/s12_ablation.py [n_captions]
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np
import torch
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
from adapters import ADAPTERS, BLOCKS, KINDS, SAMPLERS, bench, block, kind, load_factors  # noqa: E402
from s7_quality import ROOT as QUALITY  # noqa: E402
from s7_quality import STEPS, coco_items  # noqa: E402

from wspd import config  # noqa: E402

HOSTS = ["lcm", "tcd", "pcm", "hyper4"]
ROOT = config.RUNS / "study" / "quality_ablation"


def sample(b, item: dict, sampler: str) -> np.ndarray:
    """One 4-step image without guidance for a COCO caption, with study 7's seed."""
    device = b.device
    cond = b.encode(item["caption"])
    sched = SAMPLERS[sampler](b.sched_cfg)
    sched.set_timesteps(STEPS, device=device)
    seed = item["image_id"]
    z = torch.randn((1, 4, 64, 64), generator=torch.Generator("cpu").manual_seed(seed)).to(device) * sched.init_noise_sigma
    noise = torch.Generator("cpu").manual_seed(seed + 1)
    for t in sched.timesteps:
        eps = b.unet(sched.scale_model_input(z, t), t, encoder_hidden_states=cond).sample
        extra = {"generator": noise} if sampler != "ddim" else {}
        z = sched.step(eps, t, z, **extra, return_dict=False)[0]
    x = b.vae.decode(z / b.vae.config.scaling_factor).sample
    return ((x.clamp(-1, 1) + 1) * 127.5).round().permute(0, 2, 3, 1).byte().cpu().numpy()[0]


def main() -> None:
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 50
    items = coco_items(n)
    b = bench()
    arms, energy = {}, {}
    for h in HOSTS:
        f = load_factors(h)
        total = sum(float((s**2).sum()) for _, s, _ in f.values())
        share = lambda keep: sum(float((f[n][1] ** 2).sum()) for n in f if keep(n)) / total  # noqa: E731
        for blk in BLOCKS:
            arms[f"{h}_drop_{blk.split('_')[0]}"] = (h, {k: v for k, v in f.items() if block(k) != blk})
            energy[f"{h}_drop_{blk.split('_')[0]}"] = share(lambda k, blk=blk: block(k) == blk)
        arms[f"{h}_only_up"] = (h, {k: v for k, v in f.items() if block(k) == "up_blocks"})
        energy[f"{h}_only_up"] = share(lambda k: block(k) != "up_blocks")
        for kd in KINDS:
            arms[f"{h}_drop_{kd.replace('_', '')}"] = (h, {k: v for k, v in f.items() if kind(k) != kd})
            energy[f"{h}_drop_{kd.replace('_', '')}"] = share(lambda k, kd=kd: kind(k) == kd)
    (config.RESULTS / "study").joinpath("s12_removed_energy.json").write_text(__import__("json").dumps(energy, indent=1))

    # The reference arms were generated by study 7 with the same captions, seeds and sampling code.
    for name in [f"{h}_full" for h in HOSTS] + [f"none_{s}" for s in sorted({ADAPTERS[h].sampler for h in HOSTS})]:
        (ROOT / name).mkdir(parents=True, exist_ok=True)
        for i in range(n):
            link = ROOT / name / f"{i:05d}.png"
            if not link.exists():
                link.symlink_to(QUALITY / name / f"{i:05d}.png")

    for name, (h, parts) in arms.items():
        folder = ROOT / name
        folder.mkdir(parents=True, exist_ok=True)
        todo = [(i, it) for i, it in enumerate(items) if not (folder / f"{i:05d}.png").exists()]
        if not todo:
            continue
        t0 = time.time()
        b.install(parts)
        for i, it in todo:
            Image.fromarray(sample(b, it, ADAPTERS[h].sampler)).save(folder / f"{i:05d}.png")
        b.install(None)
        print(f"{name:22s} | removed energy {energy[name]:.3f} | {len(todo)} images | {time.time() - t0:4.0f} s", flush=True)


if __name__ == "__main__":
    main()
